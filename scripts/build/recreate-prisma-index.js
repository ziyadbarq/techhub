#!/usr/bin/env node

/**
 * Recreate Prisma Entry Points
 *
 * This script automatically regenerates Prisma entry points after `prisma generate`.
 *
 * Entry Points Created:
 * - index.ts   - Browser-safe default (exports from browser.ts)
 * - server.ts  - Server-only with guard (exports from client.ts)
 * - types.ts   - Explicit browser-safe alias
 *
 * Why needed:
 * - Prisma 7's client.ts imports Node.js modules (node:process, node:path, node:url)
 * - These modules break when bundled for client components
 * - browser.ts is safe for both client and server components
 * - server.ts uses `server-only` package to prevent accidental client imports
 *
 * Import Patterns:
 * - Client components: import from "@/generated/prisma" (safe default)
 * - Server components needing PrismaClient: import from "@/generated/prisma/server"
 * - Explicit enums: import from "@/generated/prisma/enums"
 *
 * This script runs automatically after `prisma generate` via the postgenerate hook.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const generatedDir = path.join(__dirname, '../src/generated/prisma');

// 1. index.ts - Browser-safe default (SAFE FOR CLIENT COMPONENTS)
const indexContent = `/**
 * Prisma barrel export - Browser-safe types and enums
 *
 * This file exports browser-safe types and enums only.
 * Safe to import in both client and server components.
 *
 * For PrismaClient (server-only), use:
 *   import { PrismaClient, Prisma } from "@/generated/prisma/server"
 *
 * For explicit enums:
 *   import { ServiceType } from "@/generated/prisma/enums"
 *
 * This file is auto-generated by scripts/recreate-prisma-index.js
 * DO NOT edit manually - changes will be overwritten on next \`prisma generate\`.
 */
export * from "./browser";
`;

// 2. server.ts - Server-only with guard (WILL ERROR IF IMPORTED IN CLIENT)
const serverContent = `/**
 * Server-only Prisma exports with PrismaClient
 *
 * This file should ONLY be imported in:
 * - Server Components (no "use client" directive)
 * - Server Actions (functions with "use server")
 * - API routes
 * - Repositories and infrastructure layer
 *
 * ⚠️ Importing this in client components will cause a BUILD ERROR.
 *
 * This file is auto-generated by scripts/recreate-prisma-index.js
 * DO NOT edit manually - changes will be overwritten on next \`prisma generate\`.
 */
import "server-only";

export * from "./client";
`;

// 3. types.ts - Explicit browser-safe alias
const typesContent = `/**
 * Browser-safe Prisma type exports
 *
 * This file is safe to import in both client and server components.
 * It exports ONLY types and enums - no runtime Node.js dependencies.
 *
 * Use this for:
 * - Type annotations in client components
 * - Enum values (e.g., ServiceType, TargetObjectTypeEnum)
 * - Model types for props/state
 *
 * This file is auto-generated by scripts/recreate-prisma-index.js
 * DO NOT edit manually - changes will be overwritten on next \`prisma generate\`.
 */
export * from "./browser";
`;

try {
  // Ensure the directory exists
  if (!fs.existsSync(generatedDir)) {
    fs.mkdirSync(generatedDir, { recursive: true });
  }

  // Write all entry point files
  fs.writeFileSync(path.join(generatedDir, 'index.ts'), indexContent, 'utf8');
  fs.writeFileSync(path.join(generatedDir, 'server.ts'), serverContent, 'utf8');
  fs.writeFileSync(path.join(generatedDir, 'types.ts'), typesContent, 'utf8');

  console.log('✓ Successfully regenerated Prisma entry points:');
  console.log('  - index.ts  (browser-safe default)');
  console.log('  - server.ts (server-only with guard)');
  console.log('  - types.ts  (explicit browser-safe)');
} catch (error) {
  console.error('✗ Failed to regenerate Prisma entry points:', error.message);
  process.exit(1);
}
