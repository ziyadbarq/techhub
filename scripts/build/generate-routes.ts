#!/usr/bin/env tsx
/**
 * Route Manifest Generator
 *
 * Generates navigation groups and protected routes from the routes manifest.
 *
 * Usage:
 *   npm run generate:routes
 *   # or
 *   tsx scripts/generate-routes.ts
 *
 * Outputs:
 *   - src/config/navigation-groups/*.ts (navigation UI structure)
 *   - src/config/protected-routes.ts (route-level permissions)
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";
import type { LucideIcon } from "lucide-react";
import {
  ROUTES_MANIFEST,
  NAV_GROUPS,
  PUBLIC_ROUTES,
  ICON_NAME_MAP,
  getRoutesByNavGroup,
  type NavGroupId,
  type RouteDefinition,
} from "../../src/config/routes-manifest";

const GENERATION_TIMESTAMP = new Date().toISOString();
const GENERATOR_VERSION = "1.0.0";

/**
 * Generate file header with auto-generation warning
 */
function generateFileHeader(sourceFile: string): string {
  return `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 *
 * This file is automatically generated from: ${sourceFile}
 * Generator version: ${GENERATOR_VERSION}
 * Generated at: ${GENERATION_TIMESTAMP}
 *
 * To modify these routes:
 * 1. Edit src/config/routes-manifest.ts
 * 2. Run: npm run generate:routes
 *
 * Manual edits will be lost on next generation.
 */

/* eslint-disable */
// @ts-nocheck
`;
}

/**
 * Convert permission value to constant name
 * e.g., "users:view" → "USERS_VIEW"
 * e.g., "dashboard:analytics" → "DASHBOARD_ANALYTICS"
 */
function permissionValueToConstantName(value: string): string {
  return value.replace(/:/g, "_").replace(/-/g, "_").toUpperCase();
}

/**
 * Extract icon name from Lucide icon component using the icon map
 */
function getIconName(icon: unknown): string {
  // Look up the icon in our mapping
  const iconName = ICON_NAME_MAP.get(icon as LucideIcon);
  if (iconName) {
    return iconName;
  }

  // Fallback: try displayName
  if (
    typeof icon === "object" &&
    icon !== null &&
    "displayName" in icon &&
    typeof icon.displayName === "string"
  ) {
    return icon.displayName;
  }
  if (
    typeof icon === "object" &&
    icon !== null &&
    "render" in icon &&
    typeof icon.render === "object" &&
    icon.render !== null &&
    "displayName" in icon.render &&
    typeof icon.render.displayName === "string"
  ) {
    return icon.render.displayName;
  }

  // Last resort fallback
  console.warn(
    `Warning: Icon not found in ICON_NAME_MAP, using fallback for:`,
    icon,
  );
  return "Home";
}

/**
 * Generate navigation group file for a specific group
 */
function generateNavGroupFile(groupId: NavGroupId): string {
  const group = NAV_GROUPS[groupId];
  const routes = getRoutesByNavGroup(groupId);

  // Filter only routes visible in navigation
  const visibleRoutes = routes.filter((route) => route.visibleInNav !== false);

  if (visibleRoutes.length === 0) {
    console.warn(`Warning: Nav group "${groupId}" has no visible routes`);
  }

  // Extract unique icons
  const icons = new Set<string>();
  visibleRoutes.forEach((route) => {
    const iconName = route.iconName || getIconName(route.icon);
    icons.add(iconName);
  });

  const iconImports = Array.from(icons).sort().join(",\n  ");

  const navItems = visibleRoutes
    .map((route) => {
      const iconName = route.iconName || getIconName(route.icon);
      const parts: string[] = [];

      parts.push(`    {`);
      parts.push(`      title: "${route.label}",`);
      parts.push(`      href: "${route.path}",`);
      parts.push(`      icon: ${iconName},`);

      if (route.description) {
        parts.push(`      description: "${route.description}",`);
      }

      if (route.requiredPermissions && route.requiredPermissions.length > 0) {
        // Take the first permission as the primary one
        const primaryPermission = route.requiredPermissions[0];
        parts.push(`      permission: PERMISSIONS.${primaryPermission},`);
      }

      if (route.featureFlag) {
        parts.push(`      featureFlag: "${route.featureFlag}",`);
      }

      if (route.badge) {
        parts.push(`      badge: "${route.badge}",`);
      }

      if (route.visibleInNav === false) {
        parts.push(`      visible: false,`);
      }

      parts.push(`    }`);

      return parts.join("\n");
    })
    .join(",\n");

  // Handle group-level permission
  const groupPermission = group.permission
    ? `\n  permission: PERMISSIONS.${permissionValueToConstantName(group.permission)},`
    : "";

  return `${generateFileHeader("src/config/routes-manifest.ts")}
import {
  ${iconImports},
} from "lucide-react";
import { PERMISSIONS } from "@/core/domain/value-objects/permission-key";
import type { NavGroup } from "../navigation.types";

export const ${groupId.replace(/-/g, "")}NavGroup: NavGroup = {
  id: "${groupId}",
  title: "${group.title}",
  items: [
${navItems}
  ],
  visible: true,
  collapsible: ${group.collapsible},${group.defaultCollapsed !== undefined ? `\n  defaultCollapsed: ${group.defaultCollapsed},` : ""}${groupPermission}
};
`;
}

/**
 * Generate protected routes configuration
 */
function generateProtectedRoutesFile(): string {
  // Group routes by parent path for organization
  const routesBySection = new Map<string, RouteDefinition[]>();

  ROUTES_MANIFEST.forEach((route) => {
    // Determine section based on path prefix
    const section =
      route.navGroup || route.path.split("/").filter(Boolean)[0] || "other";
    if (!routesBySection.has(section)) {
      routesBySection.set(section, []);
    }
    routesBySection.get(section)!.push(route);
  });

  const routeEntries: string[] = [];

  // Sort sections for consistent output
  const sortedSections = Array.from(routesBySection.keys()).sort();

  sortedSections.forEach((section) => {
    const routes = routesBySection.get(section)!;

    routeEntries.push(
      `  // ============================================================================`,
    );
    routeEntries.push(`  // ${section.toUpperCase()} ROUTES`);
    routeEntries.push(
      `  // ============================================================================`,
    );
    routeEntries.push("");

    routes.forEach((route) => {
      const parts: string[] = [];
      parts.push(`  "${route.path}": {`);

      if (route.requiredPermissions && route.requiredPermissions.length > 0) {
        const perms = route.requiredPermissions
          .map((p) => `PERMISSIONS.${p}`)
          .join(", ");
        parts.push(`    requiredPermissions: [${perms}],`);
      }

      if (
        route.requiredAllPermissions &&
        route.requiredAllPermissions.length > 0
      ) {
        const perms = route.requiredAllPermissions
          .map((p) => `PERMISSIONS.${p}`)
          .join(", ");
        parts.push(`    requiredAllPermissions: [${perms}],`);
      }

      if (route.requiredRoles && route.requiredRoles.length > 0) {
        const roles = route.requiredRoles.map((r) => `"${r}"`).join(", ");
        parts.push(`    requiredRoles: [${roles}],`);
      }

      if (route.description) {
        parts.push(`    description: "${route.description}",`);
      }

      parts.push(`  },`);
      routeEntries.push(parts.join("\n"));
    });

    routeEntries.push("");
  });

  return `${generateFileHeader("src/config/routes-manifest.ts")}
import {
  PERMISSIONS,
  type PermissionKey,
} from "@/core/domain/value-objects/permission-key";

export interface RouteProtection {
  /**
   * Permissions required to access this route
   * User must have ANY of these permissions (OR logic)
   */
  requiredPermissions?: PermissionKey[];
  /**
   * Permissions required to access this route
   * User must have ALL of these permissions (AND logic)
   */
  requiredAllPermissions?: PermissionKey[];
  /**
   * Roles required to access this route
   * User must have ANY of these roles (OR logic)
   */
  requiredRoles?: string[];
  /**
   * Description of what this route is for
   */
  description?: string;
}

/**
 * Protected routes configuration map
 * Key: Route path pattern
 * Value: Route protection configuration
 */
export const PROTECTED_ROUTES: Record<string, RouteProtection> = {
${routeEntries.join("\n")}
};

/**
 * Public routes that don't require authentication
 */
export const PUBLIC_ROUTES = [
${PUBLIC_ROUTES.map((route) => `  "${route}",`).join("\n")}
] as const;

/**
 * Check if a route is public
 */
export function isPublicRoute(pathname: string): boolean {
  return PUBLIC_ROUTES.some((route) => {
    // Exact match for root route to avoid matching all routes
    if (route === "/") {
      return pathname === "/";
    }
    // For other routes, match exact or startsWith pattern
    return pathname === route || pathname.startsWith(route);
  });
}

/**
 * Get protection config for a route
 * Handles dynamic routes with [id] pattern
 */
export function getRouteProtection(pathname: string): RouteProtection | null {
  // Exact match
  if (PROTECTED_ROUTES[pathname]) {
    return PROTECTED_ROUTES[pathname];
  }

  // Try to match dynamic routes
  // e.g., /tasks/123 matches /tasks/[id]
  for (const [pattern, protection] of Object.entries(PROTECTED_ROUTES)) {
    if (pattern.includes("[")) {
      const regexPattern = pattern
        .replace(/\\[.*?\\]/g, "[^/]+") // Replace [id] with regex pattern
        .replace(/\\//g, "\\\\/"); // Escape forward slashes
      const regex = new RegExp(\`^\${regexPattern}$\`);

      if (regex.test(pathname)) {
        return protection;
      }
    }
  }

  return null;
}

/**
 * Get all routes that require a specific permission
 */
export function getRoutesByPermission(
  permission: PermissionKey,
): Array<{ path: string; protection: RouteProtection }> {
  return Object.entries(PROTECTED_ROUTES)
    .filter(
      ([_path, protection]) =>
        protection.requiredPermissions?.includes(permission) ||
        protection.requiredAllPermissions?.includes(permission),
    )
    .map(([path, protection]) => ({ path, protection }));
}

/**
 * Get all protected route paths
 */
export function getAllProtectedRoutes(): string[] {
  return Object.keys(PROTECTED_ROUTES);
}

/**
 * Check if user has access to route based on permissions
 * This is a helper for client-side route protection
 */
export function canAccessRoute(
  pathname: string,
  userPermissions: PermissionKey[],
): boolean {
  const protection = getRouteProtection(pathname);

  if (!protection) {
    // No protection configured = allow access
    return true;
  }

  // Check required permissions (OR logic - user needs ANY)
  if (protection.requiredPermissions) {
    const hasAnyPermission = protection.requiredPermissions.some((permission) =>
      userPermissions.includes(permission),
    );
    if (!hasAnyPermission) {
      return false;
    }
  }

  // Check required all permissions (AND logic - user needs ALL)
  if (protection.requiredAllPermissions) {
    const hasAllPermissions = protection.requiredAllPermissions.every(
      (permission) => userPermissions.includes(permission),
    );
    if (!hasAllPermissions) {
      return false;
    }
  }

  return true;
}
`;
}

/**
 * Main generator function
 */
function generateRoutes() {
  console.log("🚀 Starting route generation...\n");

  const outputDir = join(process.cwd(), "src", "config");
  const navGroupsDir = join(outputDir, "navigation-groups");

  // Ensure output directories exist
  mkdirSync(navGroupsDir, { recursive: true });

  // Generate navigation group files
  console.log("📁 Generating navigation groups...");
  let navGroupsGenerated = 0;

  Object.keys(NAV_GROUPS).forEach((groupId) => {
    const navGroupFile = generateNavGroupFile(groupId as NavGroupId);
    const filename = `${groupId}.ts`;
    const filepath = join(navGroupsDir, filename);

    writeFileSync(filepath, navGroupFile, "utf-8");
    console.log(`  ✅ Generated: navigation-groups/${filename}`);
    navGroupsGenerated++;
  });

  // Generate protected routes file
  console.log("\n🔒 Generating protected routes...");
  const protectedRoutesFile = generateProtectedRoutesFile();
  const protectedRoutesPath = join(outputDir, "protected-routes.ts");

  writeFileSync(protectedRoutesPath, protectedRoutesFile, "utf-8");
  console.log(`  ✅ Generated: protected-routes.ts`);

  // Summary
  console.log("\n✨ Generation complete!");
  console.log(`  📊 Total routes in manifest: ${ROUTES_MANIFEST.length}`);
  console.log(`  📁 Navigation groups generated: ${navGroupsGenerated}`);
  console.log(
    `  🔒 Protected routes generated: ${ROUTES_MANIFEST.length} routes`,
  );
  console.log("\n📝 Next steps:");
  console.log("  1. Review generated files for correctness");
  console.log("  2. Run: npm run validate (to check types and lint)");
  console.log("  3. Commit the generated files with the manifest");
  console.log(
    "\n⚠️  Remember: DO NOT manually edit generated files. Update routes-manifest.ts instead.",
  );
}

// Run generator
try {
  generateRoutes();
  process.exit(0);
} catch (error) {
  console.error("\n❌ Generation failed:", error);
  process.exit(1);
}
