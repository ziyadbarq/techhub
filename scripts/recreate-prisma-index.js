#!/usr/bin/env node

/**
 * Recreate Prisma Barrel Export
 *
 * This script automatically regenerates src/generated/prisma/index.ts after `prisma generate`.
 *
 * Why needed:
 * - Prisma 7 no longer generates a barrel export index.ts by default
 * - The codebase uses `import X from "@/generated/prisma"` convention
 * - Without index.ts, TypeScript compilation fails with module not found errors
 * - Pre-commit hooks fail when this file is missing
 *
 * This script runs automatically after `prisma generate` via the postgenerate hook.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const indexPath = path.join(__dirname, '../src/generated/prisma/index.ts');

const content = `/**
 * Prisma barrel export
 * Use this module for all Prisma imports to comply with project conventions.
 *
 * This file is auto-generated by the postgenerate script (scripts/recreate-prisma-index.js).
 * DO NOT edit manually - changes will be overwritten on next \`prisma generate\`.
 */
export * from "./client";
`;

try {
  // Ensure the directory exists
  const dir = path.dirname(indexPath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  // Write the index.ts file
  fs.writeFileSync(indexPath, content, 'utf8');

  console.log('✓ Successfully regenerated src/generated/prisma/index.ts');
} catch (error) {
  console.error('✗ Failed to regenerate src/generated/prisma/index.ts:', error.message);
  process.exit(1);
}
