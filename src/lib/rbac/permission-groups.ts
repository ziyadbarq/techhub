/**
 * Get all permissions in a flat array
 */
export function getAllGroupedPermissions(): PermissionKey[] {
  return PERMISSION_GROUPS.flatMap((group) => group.permissions);
}

/**
 * Get group by permission key
 */
export function getGroupByPermission(
  permission: PermissionKey,
): PermissionGroup | undefined {
  return PERMISSION_GROUPS.find((group) =>
    group.permissions.includes(permission),
  );
}

/**
 * Get permissions by group ID
 */
export function getPermissionsByGroupId(groupId: string): PermissionKey[] {
  const group = PERMISSION_GROUPS.find((g) => g.id === groupId);
  return group?.permissions ?? [];
}

/**
 * Check if a permission is in a specific group
 */
export function isPermissionInGroup(
  permission: PermissionKey,
  groupId: string,
): boolean {
  const group = PERMISSION_GROUPS.find((g) => g.id === groupId);
  return group?.permissions.includes(permission) ?? false;
}

/**
 * Get permission count by group
 */
export function getGroupPermissionCount(groupId: string): number {
  const group = PERMISSION_GROUPS.find((g) => g.id === groupId);
  return group?.permissions.length ?? 0;
}
