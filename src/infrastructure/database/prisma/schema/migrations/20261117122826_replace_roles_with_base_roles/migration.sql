  ('role_asset_manager', 'asset-manager', 'Asset Manager', 'Full control of assets, inventory, licenses, contracts, vendors and locations, including approvals, settings and reports', false, true, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP),
