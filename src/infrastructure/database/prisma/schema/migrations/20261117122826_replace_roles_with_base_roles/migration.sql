CREATE TEMP TABLE "role_id_moves" AS
SELECT o."id" AS "old_id", m_role."id" AS "member_id", r_role."id" AS "reference_id"
FROM "role_moves" m
JOIN "roles" o ON o."name" = m."old_name"
JOIN "roles" m_role ON m_role."name" = m."member_role"
JOIN "roles" r_role ON r_role."name" = m."reference_role";

-- 4. Members: one row per user and new role. Permanent wins over expiring;
--    otherwise the latest expiry is kept.
INSERT INTO "user_roles" ("id", "userId", "roleId", "expiresAt", "createdAt", "createdBy")
SELECT 'ur_' || md5(ur."userId" || ':' || mv."member_id"), ur."userId", mv."member_id",
       CASE WHEN bool_or(ur."expiresAt" IS NULL) THEN NULL ELSE max(ur."expiresAt") END,
       min(ur."createdAt"), 'migration:replace_roles_with_base_roles'
FROM "user_roles" ur
JOIN "role_id_moves" mv ON mv."old_id" = ur."roleId"
GROUP BY ur."userId", mv."member_id"
ON CONFLICT ("userId", "roleId") DO UPDATE
SET "expiresAt" = CASE
  WHEN "user_roles"."expiresAt" IS NULL OR EXCLUDED."expiresAt" IS NULL THEN NULL
  ELSE GREATEST("user_roles"."expiresAt", EXCLUDED."expiresAt")
END;

-- 5. Everything that references a role --------------------------------------
UPDATE "lifecycle_transitions" t SET "requiredRoleId" = mv."reference_id"
FROM "role_id_moves" mv WHERE t."requiredRoleId" = mv."old_id";

UPDATE "form_notification_bindings" b SET "recipientRoleId" = mv."reference_id"
FROM "role_id_moves" mv WHERE b."recipientRoleId" = mv."old_id";

UPDATE "roles" c SET "parentId" = mv."reference_id"
FROM "role_id_moves" mv WHERE c."parentId" = mv."old_id";

-- Watcher subscriptions are unique per (form, role): drop the ones that would
-- duplicate an existing subscription, move the rest.
DELETE FROM "watcher_subscriptions" w
USING "role_id_moves" mv
WHERE w."roleId" = mv."old_id"
  AND EXISTS (
    SELECT 1 FROM "watcher_subscriptions" x
    WHERE x."formId" = w."formId" AND x."roleId" = mv."reference_id"
  );
DELETE FROM "watcher_subscriptions" w
USING "role_id_moves" mv
WHERE w."roleId" = mv."old_id"
  AND w."id" NOT IN (
    SELECT DISTINCT ON (w2."formId", mv2."reference_id") w2."id"
    FROM "watcher_subscriptions" w2
    JOIN "role_id_moves" mv2 ON mv2."old_id" = w2."roleId"
    ORDER BY w2."formId", mv2."reference_id", w2."id"
  );
UPDATE "watcher_subscriptions" w SET "roleId" = mv."reference_id"
FROM "role_id_moves" mv WHERE w."roleId" = mv."old_id";

