-- Replace the seeded role set with the base roles:
--   System Administrator (unchanged), Viewer (every employee),
--   Asset Manager, Asset Officer, CMDB Manager, Workflow Officer.
--
-- Same definitions as seed-rbac-roles (generated from them). Custom roles an
-- administrator created are not touched; only these ten seeded roles go:
-- asset-coordinator, auditor, data-steward, finance-manager, hr-manager,
-- inventory-manager, it-help-desk, maintenance-technician, security-officer,
-- service-owner.
--
-- Nobody loses access silently:
--   * members move to the nearest new role (role_moves.member_role);
--     security-officer, auditor and hr-manager members become Viewers;
--   * things that point at a role (workflow step assignees, form
--     notification recipients, watcher subscriptions, lifecycle transition
--     requirements, custom roles' parents) move to role_moves.reference_role.
--     That is never Viewer, so no step becomes approvable by everyone.
--
-- Idempotent: safe to run on a database that already has the new roles.
-- Effective within the 5-minute permission cache TTL.

-- 1. The roles -------------------------------------------------------------
INSERT INTO "roles" ("id", "name", "displayName", "description", "isSystem", "isActive", "createdAt", "updatedAt")
VALUES
