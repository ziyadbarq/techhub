-- Viewer already exists everywhere; give it the new description unless an
-- administrator has written their own.
UPDATE "roles"
SET "description" = 'Employee self-service: dashboard, own requests, assigned approvals and the knowledge base',
    "updatedAt" = CURRENT_TIMESTAMP
WHERE "name" = 'viewer'
  AND "description" IS NOT DISTINCT FROM 'Minimal access - dashboard and documentation only';

