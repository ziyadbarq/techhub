/**
 * Void Movement Dialog Component
 *
 * Modal dialog for voiding a stock movement with reason capture.
 * Preserves audit trail by requiring a void reason.
 */

"use client";

import { useState } from "react";
import { useForm } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import { z } from "zod";
import { toast } from "sonner";
import { Ban, Loader2, AlertTriangle } from "lucide-react";
import { Button } from "@/components/ui/button";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import {
  Form,
  FormControl,
  FormField,
  FormItem,
  FormLabel,
  FormMessage,
} from "@/components/ui/form";
import { Textarea } from "@/components/ui/textarea";
import { Alert, AlertDescription } from "@/components/ui/alert";
import type { StockMovementDTO } from "@/interface-adapters/presenters/stock-movement.presenter";
import { voidStockMovementAction } from "@/interface-adapters/controllers/stock-movement.controller";

const voidFormSchema = z.object({
  voidReason: z
    .string()
    .min(1, "Void reason is required")
    .max(5000, "Reason must be 5000 characters or less"),
});

type VoidFormValues = z.infer<typeof voidFormSchema>;

interface VoidMovementDialogProps {
  movement: StockMovementDTO | null;
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onVoided?: (movement: StockMovementDTO) => void;
  personId: string;
}

export function VoidMovementDialog({
  movement,
  open,
  onOpenChange,
  onVoided,
  personId,
}: VoidMovementDialogProps) {
  const [isSubmitting, setIsSubmitting] = useState(false);

  const form = useForm<VoidFormValues>({
    resolver: zodResolver(voidFormSchema),
    defaultValues: {
      voidReason: "",
    },
  });

  const handleClose = () => {
    form.reset();
    onOpenChange(false);
  };

  const onSubmit = async (values: VoidFormValues) => {
    if (!movement) return;

    setIsSubmitting(true);
    try {
      const result = await voidStockMovementAction({
        id: movement.id,
        voidedById: personId,
        voidReason: values.voidReason,
      });

      if (result.success) {
        toast.success("Movement voided successfully");
        onVoided?.(result.data);
        handleClose();
      } else {
        toast.error(result.error || "Failed to void movement");
      }
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : "Failed to void movement",
      );
    } finally {
      setIsSubmitting(false);
    }
  };

  if (!movement) return null;

  const isAutoGenerated = movement.isAutoGenerated;

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="sm:max-w-[425px]">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            <Ban className="text-destructive h-5 w-5" />
            Void Stock Movement
          </DialogTitle>
          <DialogDescription>
            This will mark the movement as voided. The movement record will be
            preserved for audit purposes but will no longer be counted in
            inventory calculations.
          </DialogDescription>
        </DialogHeader>

        {isAutoGenerated && (
          <Alert variant="destructive">
            <AlertTriangle className="h-4 w-4" />
            <AlertDescription>
              This movement was automatically generated by the system (
              {movement.source.replace("_", " ").toLowerCase()}). Voiding it may
              cause inconsistencies in tracking.
            </AlertDescription>
          </Alert>
        )}

        <Form {...form}>
          <form onSubmit={form.handleSubmit(onSubmit)} className="space-y-4">
            <div className="rounded-md border p-3 text-sm">
              <div className="grid gap-1">
                <div className="flex justify-between">
                  <span className="text-muted-foreground">Type:</span>
                  <span className="font-medium">{movement.movementType}</span>
                </div>
                {movement.stockLocationFromName && (
                  <div className="flex justify-between">
                    <span className="text-muted-foreground">From:</span>
                    <span>{movement.stockLocationFromName}</span>
                  </div>
                )}
                {movement.stockLocationToName && (
                  <div className="flex justify-between">
                    <span className="text-muted-foreground">To:</span>
                    <span>{movement.stockLocationToName}</span>
                  </div>
                )}
                <div className="flex justify-between">
                  <span className="text-muted-foreground">Quantity:</span>
                  <span>{movement.quantity}</span>
                </div>
                {movement.performedByName && (
                  <div className="flex justify-between">
                    <span className="text-muted-foreground">Performed by:</span>
                    <span>{movement.performedByName}</span>
                  </div>
                )}
              </div>
            </div>

            <FormField
              control={form.control}
              name="voidReason"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>Reason for Voiding *</FormLabel>
                  <FormControl>
                    <Textarea
                      placeholder="Explain why this movement is being voided..."
                      className="min-h-[100px] resize-none"
                      {...field}
                    />
                  </FormControl>
                  <FormMessage />
                </FormItem>
              )}
            />

            <DialogFooter>
              <Button
                type="button"
                variant="outline"
                onClick={handleClose}
                disabled={isSubmitting}
              >
                Cancel
              </Button>
              <Button
                type="submit"
                variant="destructive"
                disabled={isSubmitting}
              >
                {isSubmitting && (
                  <Loader2 className="mr-2 h-4 w-4 animate-spin" />
                )}
                Void Movement
              </Button>
            </DialogFooter>
          </form>
        </Form>
      </DialogContent>
    </Dialog>
  );
}
