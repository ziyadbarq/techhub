/**
 * Movement Detail Sheet Component
 *
 * Slide-out panel showing complete details of a stock movement.
 * Includes status, source tracking, void information, and links to related entities.
 */

"use client";

import { format } from "date-fns";
import {
  ArrowDown,
  ArrowUp,
  ArrowUpDown,
  Package,
  ArrowRight,
  Ban,
  Bot,
  User,
  Calendar,
  Hash,
  FileText,
  Link2,
  Clock,
} from "lucide-react";
import {
  Sheet,
  SheetContent,
  SheetDescription,
  SheetHeader,
  SheetTitle,
} from "@/components/ui/sheet";
import { Badge } from "@/components/ui/badge";
import { Separator } from "@/components/ui/separator";
import { Button } from "@/components/ui/button";
import type { StockMovementDTO } from "@/interface-adapters/presenters/stock-movement.presenter";
import type { StockMovementSource } from "@/core/domain/entities/stock-movement.entity";

type MovementType = "IN" | "OUT" | "TRANSFER" | "ADJUSTMENT";

interface MovementDetailSheetProps {
  movement: StockMovementDTO | null;
  open: boolean;
  onOpenChange: (open: boolean) => void;
  onVoid?: (movement: StockMovementDTO) => void;
  canVoid?: boolean;
}

const movementTypeIcons: Record<MovementType, typeof ArrowDown> = {
  IN: ArrowDown,
  OUT: ArrowUp,
  TRANSFER: ArrowUpDown,
  ADJUSTMENT: Package,
};

const movementTypeLabels: Record<MovementType, string> = {
  IN: "Received into Inventory",
  OUT: "Issued from Inventory",
  TRANSFER: "Transferred between Locations",
  ADJUSTMENT: "Inventory Adjustment",
};

const movementTypeColors: Record<MovementType, string> = {
  IN: "bg-green-500/10 text-green-700 dark:text-green-400",
  OUT: "bg-blue-500/10 text-blue-700 dark:text-blue-400",
  TRANSFER: "bg-purple-500/10 text-purple-700 dark:text-purple-400",
  ADJUSTMENT: "bg-orange-500/10 text-orange-700 dark:text-orange-400",
};

const sourceLabels: Record<StockMovementSource, string> = {
  MANUAL: "Manual Entry",
  ASSIGNMENT: "Asset Assignment",
  RETURN: "Asset Return",
  DISPOSAL: "Asset Disposal",
  IMPORT: "Data Import",
  LOCATION_CHANGE: "Location Change",
  SYSTEM: "System Generated",
};

const sourceDescriptions: Record<StockMovementSource, string> = {
  MANUAL: "Created manually by a user",
  ASSIGNMENT: "Generated when assigning asset to an employee",
  RETURN: "Generated when returning asset to inventory",
  DISPOSAL: "Generated when disposing of an asset",
  IMPORT: "Generated during data import",
  LOCATION_CHANGE: "Generated when updating asset location",
  SYSTEM: "Generated by system automation",
};

function DetailRow({
  icon: Icon,
  label,
  children,
}: {
  icon: typeof Calendar;
  label: string;
  children: React.ReactNode;
}) {
  return (
    <div className="flex items-start gap-3 py-2">
      <Icon className="text-muted-foreground mt-0.5 h-4 w-4 shrink-0" />
      <div className="min-w-0 flex-1">
        <div className="text-muted-foreground text-xs font-medium tracking-wide uppercase">
          {label}
        </div>
        <div className="mt-0.5">{children}</div>
      </div>
    </div>
  );
}

export function MovementDetailSheet({
  movement,
  open,
  onOpenChange,
  onVoid,
  canVoid = false,
}: MovementDetailSheetProps) {
  if (!movement) return null;

  const type = movement.movementType as MovementType;
  const Icon = movementTypeIcons[type] || Package;
  const colorClass = movementTypeColors[type] || "";
  const source = movement.source as StockMovementSource;

  return (
    <Sheet open={open} onOpenChange={onOpenChange}>
      <SheetContent className="overflow-y-auto sm:max-w-lg">
        <SheetHeader>
          <div className="flex items-center gap-3">
            <div className={`rounded-lg p-2 ${colorClass}`}>
              <Icon className="h-5 w-5" />
            </div>
            <div>
              <SheetTitle className="flex items-center gap-2">
                {movement.movementType}
                {movement.isVoided && (
                  <Badge variant="destructive">Voided</Badge>
                )}
              </SheetTitle>
              <SheetDescription>{movementTypeLabels[type]}</SheetDescription>
            </div>
          </div>
        </SheetHeader>

        <div className="mt-6 space-y-6">
          {/* Voided Alert */}
          {movement.isVoided && (
            <div className="rounded-lg border border-dashed border-red-300 bg-red-50 p-4 dark:border-red-900 dark:bg-red-950/30">
              <div className="flex items-center gap-2 font-medium text-red-700 dark:text-red-400">
                <Ban className="h-4 w-4" />
                Movement Voided
              </div>
              {movement.voidedAt && (
                <p className="mt-1 text-sm text-red-600 dark:text-red-400">
                  {format(
                    new Date(movement.voidedAt),
                    "MMMM d, yyyy 'at' h:mm a",
                  )}
                </p>
              )}
              {movement.voidReason && (
                <p className="mt-2 text-sm text-red-600 dark:text-red-400">
                  <strong>Reason:</strong> {movement.voidReason}
                </p>
              )}
              {movement.voidedByName && (
                <p className="text-muted-foreground mt-1 text-xs">
                  Voided by: {movement.voidedByName}
                </p>
              )}
            </div>
          )}

          {/* Location Flow */}
          <div>
            <h4 className="text-muted-foreground mb-2 text-xs font-medium tracking-wide uppercase">
              {movement.source === "ASSIGNMENT" || movement.source === "RETURN"
                ? "Assignment Flow"
                : "Location Flow"}
            </h4>
            <div className="flex items-center gap-3 rounded-lg border p-3">
              <div className="min-w-0 flex-1 text-center">
                <div className="text-muted-foreground text-xs">
                  {movement.source === "RETURN" ? "Returned By" : "From"}
                </div>
                <div className="mt-1 truncate font-medium">
                  {movement.source === "RETURN" && movement.assignedToName ? (
                    <span className="flex items-center justify-center gap-1">
                      <User className="h-3.5 w-3.5" />
                      {movement.assignedToName}
                    </span>
                  ) : movement.stockLocationFromName ? (
                    movement.stockLocationFromName
                  ) : (
                    <span className="text-muted-foreground/50 italic">
                      External
                    </span>
                  )}
                </div>
              </div>
              <ArrowRight className="text-muted-foreground h-4 w-4 shrink-0" />
              <div className="min-w-0 flex-1 text-center">
                <div className="text-muted-foreground text-xs">
                  {movement.source === "ASSIGNMENT" ? "Assigned To" : "To"}
                </div>
                <div className="mt-1 truncate font-medium">
                  {movement.source === "ASSIGNMENT" &&
                  movement.assignedToName ? (
                    <span className="flex items-center justify-center gap-1">
                      <User className="h-3.5 w-3.5" />
                      {movement.assignedToName}
                    </span>
                  ) : movement.stockLocationToName ? (
                    movement.stockLocationToName
                  ) : (
                    <span className="text-muted-foreground/50 italic">
                      External
                    </span>
                  )}
                </div>
              </div>
            </div>
          </div>

          <Separator />

          {/* Details */}
          <div>
            <h4 className="text-muted-foreground mb-2 text-xs font-medium tracking-wide uppercase">
              Details
            </h4>
            <div className="space-y-1">
              <DetailRow icon={Calendar} label="Occurred At">
                {format(
                  new Date(movement.occurredAt),
                  "MMMM d, yyyy 'at' h:mm a",
                )}
              </DetailRow>

              <DetailRow icon={Clock} label="Created At">
                {format(
                  new Date(movement.createdAt),
                  "MMMM d, yyyy 'at' h:mm a",
                )}
              </DetailRow>

              <DetailRow icon={Hash} label="Quantity">
                {movement.quantity}
              </DetailRow>

              <DetailRow icon={User} label="Performed By">
                {movement.performedByName || (
                  <span className="text-muted-foreground">Unknown</span>
                )}
              </DetailRow>

              {movement.reason && (
                <DetailRow icon={FileText} label="Reason">
                  {movement.reason}
                </DetailRow>
              )}
            </div>
          </div>

          <Separator />

          {/* Source Tracking */}
          <div>
            <h4 className="text-muted-foreground mb-2 text-xs font-medium tracking-wide uppercase">
              Source Tracking
            </h4>
            <div className="space-y-3">
              <div className="flex items-center gap-2">
                {movement.isAutoGenerated ? (
                  <Bot className="text-muted-foreground h-4 w-4" />
                ) : (
                  <User className="text-muted-foreground h-4 w-4" />
                )}
                <Badge
                  variant={movement.isAutoGenerated ? "secondary" : "outline"}
                >
                  {sourceLabels[source]}
                </Badge>
              </div>
              <p className="text-muted-foreground text-sm">
                {sourceDescriptions[source]}
              </p>

              {movement.sourceReferenceType && (
                <div className="rounded-md border p-2 text-sm">
                  <DetailRow icon={Link2} label="Reference">
                    <div className="flex items-center gap-2">
                      <span className="text-muted-foreground">
                        {movement.sourceReferenceType}
                      </span>
                      {movement.sourceReferenceId && (
                        <code className="bg-muted rounded px-1.5 py-0.5 text-xs">
                          {movement.sourceReferenceId}
                        </code>
                      )}
                    </div>
                  </DetailRow>
                </div>
              )}
            </div>
          </div>

          <Separator />

          {/* Status */}
          <div>
            <h4 className="text-muted-foreground mb-2 text-xs font-medium tracking-wide uppercase">
              Status
            </h4>
            <div className="flex items-center gap-2">
              <Badge
                variant={movement.isActive ? "default" : "destructive"}
                className="gap-1"
              >
                {movement.isActive ? (
                  <>
                    <div className="h-1.5 w-1.5 rounded-full bg-current" />
                    Active
                  </>
                ) : (
                  <>
                    <Ban className="h-3 w-3" />
                    Voided
                  </>
                )}
              </Badge>
            </div>
          </div>

          {/* Actions */}
          {canVoid && onVoid && movement.isActive && (
            <>
              <Separator />
              <div>
                <Button
                  variant="destructive"
                  className="w-full"
                  onClick={() => {
                    onVoid(movement);
                    onOpenChange(false);
                  }}
                >
                  <Ban className="mr-2 h-4 w-4" />
                  Void this Movement
                </Button>
                <p className="text-muted-foreground mt-2 text-center text-xs">
                  Voiding preserves the record but excludes it from calculations
                </p>
              </div>
            </>
          )}
        </div>
      </SheetContent>
    </Sheet>
  );
}
