/**
 * StockMovement Presenter
 * Transforms StockMovement domain entities to DTOs for presentation layer
 */

import type {
  StockMovement,
  StockMovementStatus,
  StockMovementSource,
} from "@/core/domain/entities/stock-movement.entity";

export interface StockMovementDTO {
  id: string;
  movementType: string;
  stockLocationFromId: string | null;
  stockLocationToId: string | null;
  assetId: string | null;
  quantity: number;
  reason: string | null;
  performedById: string;
  occurredAt: string;
  createdAt: string;
  // Status and void fields
  status: StockMovementStatus;
  voidedAt: string | null;
  voidedById: string | null;
  voidReason: string | null;
  // Source tracking
  source: StockMovementSource;
  sourceReferenceType: string | null;
  sourceReferenceId: string | null;
  // Computed fields
  isReceiving: boolean;
  isIssuing: boolean;
  isTransfer: boolean;
  isAdjustment: boolean;
  isActive: boolean;
  isVoided: boolean;
  isAutoGenerated: boolean;
  // Display fields (enriched from relations)
  stockLocationFromName?: string | null;
  stockLocationToName?: string | null;
  assetTag?: string | null;
  performedByName?: string | null;
  voidedByName?: string | null;
  // For assignment/return movements: the person involved
  assignedToName?: string | null;
}

export interface StockMovementEnrichment {
  stockLocationFromName?: string | null;
  stockLocationToName?: string | null;
  assetTag?: string | null;
  performedByName?: string | null;
  voidedByName?: string | null;
  assignedToName?: string | null;
}

export function presentStockMovement(
  movement: StockMovement,
  enrichment?: StockMovementEnrichment,
): StockMovementDTO {
  return {
    id: movement.id,
    movementType: movement.movementType,
    stockLocationFromId: movement.stockLocationFromId,
    stockLocationToId: movement.stockLocationToId,
    assetId: movement.assetId,
    quantity: movement.quantity,
    reason: movement.reason,
    performedById: movement.performedById,
    occurredAt: movement.occurredAt.toISOString(),
    createdAt: movement.createdAt.toISOString(),
    // Status and void fields
    status: movement.status,
    voidedAt: movement.voidedAt?.toISOString() ?? null,
    voidedById: movement.voidedById,
    voidReason: movement.voidReason,
    // Source tracking
    source: movement.source,
    sourceReferenceType: movement.sourceReferenceType,
    sourceReferenceId: movement.sourceReferenceId,
    // Computed fields
    isReceiving: movement.isReceiving(),
    isIssuing: movement.isIssuing(),
    isTransfer: movement.isTransfer(),
    isAdjustment: movement.isAdjustment(),
    isActive: movement.isActive(),
    isVoided: movement.isVoided(),
    isAutoGenerated: movement.isAutoGenerated(),
    // Display fields
    stockLocationFromName: enrichment?.stockLocationFromName,
    stockLocationToName: enrichment?.stockLocationToName,
    assetTag: enrichment?.assetTag,
    performedByName: enrichment?.performedByName,
    voidedByName: enrichment?.voidedByName,
    assignedToName: enrichment?.assignedToName,
  };
}

export function presentStockMovements(
  movements: StockMovement[],
  enrichmentMap?: Map<string, StockMovementEnrichment>,
): StockMovementDTO[] {
  return movements.map((movement) =>
    presentStockMovement(movement, enrichmentMap?.get(movement.id)),
  );
}
