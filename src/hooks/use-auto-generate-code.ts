/**
 * Hook for auto-generating code from name field
 *
 * Automatically populates the code field based on the name field,
 * similar to WordPress post slug generation.
 */

import { useEffect, useRef } from "react";
import type { UseFormReturn, FieldValues, Path } from "react-hook-form";
import { generateCodeFromName } from "@/lib/utils/generate-code-from-name";

interface UseAutoGenerateCodeOptions<T extends FieldValues> {
  /** The react-hook-form instance */
  form: UseFormReturn<T>;
  /** The name of the source field (default: "name") */
  nameField?: Path<T>;
  /** The name of the code field (default: "code") */
  codeField?: Path<T>;
  /** Whether we're editing an existing record (disables auto-generation) */
  isEditing?: boolean;
  /** Whether auto-generation is enabled (default: true) */
  enabled?: boolean;
}

/**
 * Auto-generates code from name field as user types
 *
 * @example
 * ```tsx
 * const form = useForm<MyFormValues>();
 *
 * useAutoGenerateCode({
 *   form,
 *   isEditing: !!existingRecord,
 * });
 * ```
 */
export function useAutoGenerateCode<T extends FieldValues>({
  form,
  nameField = "name" as Path<T>,
  codeField = "code" as Path<T>,
  isEditing = false,
  enabled = true,
}: UseAutoGenerateCodeOptions<T>) {
  // Track if user has manually edited the code field
  const userEditedCode = useRef(false);
  // Track the last auto-generated code to detect manual edits
  const lastAutoGeneratedCode = useRef("");

  const name = form.watch(nameField);
  const code = form.watch(codeField);

  // Reset tracking when form is reset or dialog closes
  useEffect(() => {
    const subscription = form.watch((_, { name: fieldName, type }) => {
      // Reset tracking when form is reset
      if (type === "change" && fieldName === undefined) {
        userEditedCode.current = false;
        lastAutoGeneratedCode.current = "";
      }
    });
    return () => subscription.unsubscribe();
  }, [form]);

  // Detect manual code edits
  useEffect(() => {
    if (!enabled || isEditing) return;

    // If code was changed and it doesn't match what we auto-generated,
    // the user manually edited it
    if (
      code &&
      lastAutoGeneratedCode.current &&
      code !== lastAutoGeneratedCode.current
    ) {
      userEditedCode.current = true;
    }
  }, [code, enabled, isEditing]);

  // Auto-generate code from name
  useEffect(() => {
    // Don't auto-generate if:
    // - Feature is disabled
    // - We're editing an existing record
    // - User has manually edited the code
    if (!enabled || isEditing || userEditedCode.current) {
      return;
    }

    const generatedCode = generateCodeFromName(name as string);

    // Only update if we have a name and the generated code is different
    if (generatedCode && generatedCode !== code) {
      lastAutoGeneratedCode.current = generatedCode;
      form.setValue(codeField, generatedCode as T[Path<T>], {
        shouldValidate: false,
        shouldDirty: true,
      });
    }
  }, [name, code, form, codeField, isEditing, enabled]);

  // Reset user edit tracking when creating a new record
  const resetTracking = () => {
    userEditedCode.current = false;
    lastAutoGeneratedCode.current = "";
  };

  return { resetTracking };
}
